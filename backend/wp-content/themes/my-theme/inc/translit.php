<?php
/**
 * =================================================================================================
 * inc/translit.php — транслитерация слагов и имён файлов (Яндекс-таблица)
 * =================================================================================================
 *
 * Перенос из боевого проекта (evakuatori/jarrayone, core/translit.php) с
 * нейтральным неймспейсом my_theme_. Русские заголовки постов/страниц/рубрик
 * получают читаемые латинские слаги («О компании» → o-kompanii), загружаемые
 * файлы — латинские имена.
 * =================================================================================================
 */

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit; // Защита от прямого вызова.
}

if ( ! function_exists( 'my_theme_yandex_translit' ) ) {
	/**
	 * Транслитерация кириллицы по Яндекс-таблице.
	 */
	function my_theme_yandex_translit( string $title ): string {
		$iso = array(
			'А' => 'a',  'Б' => 'b',  'В' => 'v',  'Г' => 'g',  'Д' => 'd',
			'Е' => 'e',  'Ё' => 'yo', 'Ж' => 'zh', 'З' => 'z',  'И' => 'i',
			'Й' => 'y',  'К' => 'k',  'Л' => 'l',  'М' => 'm',  'Н' => 'n',
			'О' => 'o',  'П' => 'p',  'Р' => 'r',  'С' => 's',  'Т' => 't',
			'У' => 'u',  'Ф' => 'f',  'Х' => 'kh', 'Ц' => 'ts', 'Ч' => 'ch',
			'Ш' => 'sh', 'Щ' => 'shch', 'Ъ' => '',   'Ы' => 'y',  'Ь' => '',
			'Э' => 'e',  'Ю' => 'yu', 'Я' => 'ya',

			'а' => 'a',  'б' => 'b',  'в' => 'v',  'г' => 'g',  'д' => 'd',
			'е' => 'e',  'ё' => 'yo', 'ж' => 'zh', 'з' => 'z',  'и' => 'i',
			'й' => 'y',  'к' => 'k',  'л' => 'l',  'м' => 'm',  'н' => 'n',
			'о' => 'o',  'п' => 'p',  'р' => 'r',  'с' => 's',  'т' => 't',
			'у' => 'u',  'ф' => 'f',  'х' => 'kh', 'ц' => 'ts', 'ч' => 'ch',
			'ш' => 'sh', 'щ' => 'shch', 'ъ' => '',   'ы' => 'y',  'ь' => '',
			'э' => 'e',  'ю' => 'yu', 'я' => 'ya',
		);

		return strtr( $title, $iso );
	}

	// Транслитерация слагов постов/страниц/рубрик при сохранении.
	add_filter(
		'sanitize_title',
		static function ( $title, $raw_title, $context ) {
			if ( $context === 'save' ) {
				$title = my_theme_yandex_translit( (string) $raw_title );
			}
			return $title;
		},
		9,
		3
	);

	// Транслитерация загружаемых картинок и файлов.
	add_filter( 'sanitize_file_name', 'my_theme_yandex_translit', 10 );
}
